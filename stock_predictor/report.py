import os
from fpdf import FPDF
from datetime import datetime

def generate_pdf_report(ticker: str, current_price: float, future_price: float, 
                        best_ml: str, hype_trend: str, sentiment_score: float, 
                        vix: float, funds: dict) -> bytes:
    """Generate a simple PDF report using FPDF and return bytes."""
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Arial", size=12)
    
    # Title
    pdf.set_font("Helvetica", 'B', 16)
    pdf.cell(200, 10, f"AI Stock Predictor Report: {ticker}", ln=1, align='C')
    pdf.set_font("Helvetica", size=10)
    pdf.cell(200, 10, f"Generated on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", ln=1, align='C')
    pdf.ln(10)
    
    # Section 1: Fundamentals & Market
    pdf.set_font("Helvetica", 'B', 14)
    pdf.cell(200, 10, "1. Fundamentals & Market Sentiment", ln=1)
    pdf.set_font("Helvetica", size=12)
    pdf.cell(200, 10, f"Current Price: {current_price:,.2f}", ln=1)
    if funds:
        pdf.cell(200, 10, f"P/E Ratio: {funds.get('PE', 'N/A')} | EPS: {funds.get('EPS', 'N/A')}", ln=1)
        
    vix_status = "Fear (High Volatility)" if vix > 20 else "Greed (Stable Market)"
    pdf.cell(200, 10, f"Market VIX Index: {vix:.2f} - {vix_status}", ln=1)
    
    pdf.cell(200, 10, f"Wikipedia Hype Trend: {hype_trend}", ln=1)
    pdf.cell(200, 10, f"News Sentiment (VADER): {sentiment_score:+.2f}", ln=1)
    pdf.ln(10)
    
    # Section 2: AI Prediction
    pdf.set_font("Helvetica", 'B', 14)
    pdf.cell(200, 10, "2. Machine Learning Prediction", ln=1)
    pdf.set_font("Helvetica", size=12)
    pdf.cell(200, 10, f"Best Performing Model: {best_ml}", ln=1)
    
    percent_change = ((future_price - current_price) / current_price) * 100
    pdf.cell(200, 10, f"Predicted Future Price (30 Days): {future_price:,.2f}", ln=1)
    pdf.cell(200, 10, f"Expected Return: {percent_change:+.2f}%", ln=1)
    pdf.ln(10)
    
    # Section 3: Recommendation
    pdf.set_font("Helvetica", 'B', 14)
    pdf.cell(200, 10, "3. Final AI Recommendation", ln=1)
    pdf.set_font("Helvetica", size=12)
    
    if percent_change > 3.0:
        base_rec = "BUY"
    elif percent_change < -3.0:
        base_rec = "SELL"
    else:
        base_rec = "HOLD"
        
    pdf.cell(200, 10, f"Technical Suggestion: {base_rec}", ln=1)
    pdf.multi_cell(0, 10, "Disclaimer: This report is generated by AI and is for educational purposes only. Do not trade real money based on this report.")
    
    return bytes(pdf.output())
